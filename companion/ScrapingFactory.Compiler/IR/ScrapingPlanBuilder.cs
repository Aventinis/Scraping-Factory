namespace ScrapingFactory.Compiler.IR;

// Translates the wire ScrapingConfig into the canonical ScrapingPlan: a NavigateStep, the browser actions, then
// one extraction step per mode. The generators and verifiers only ever see the plan.
public static class ScrapingPlanBuilder
{
    public static ScrapingPlan Build(ScrapingConfig config)
    {
        // Blank AdditionalUrls entries are dropped (a pasted list's stray empty line); a malformed non-blank
        // one is still a validation error.
        var urls = new List<string> { config.Url };
        if (config.AdditionalUrls is { Count: > 0 } additionalUrls)
        {
            urls.AddRange(additionalUrls.Select(u => u.Trim()).Where(u => u.Length > 0));
        }

        var steps = new List<ScrapingStep> { new NavigateStep { Urls = urls } };

        // Browser actions run before extraction, whatever the mode.
        if (config.BrowserActions is { Count: > 0 } actions)
            steps.AddRange(actions.Select(ToStep));

        // Sanitized here rather than trusting the wire payload.
        var scriptFileName = FileNameSanitizer.SanitizeBaseName(config.ScriptFileName, "scraper");
        var outputFileBaseName = FileNameSanitizer.SanitizeBaseName(config.OutputFileName, "output");

        // Container mode: Groups replaces Fields; the output defaults to Xml unless Json was asked for.
        if (config.Groups is { Count: > 0 } groups)
        {
            // A flat-schema blueprint flattens the tree into rows, so it needs the flat formats (Csv / flat Json);
            // a tree-schema one builds a nested structure and keeps Xml / tree Json. A table format (Sqlite/Xlsx)
            // also needs rows: without an explicit blueprint the tree gets an identity mapping over its leaves.
            var isJson = config.OutputFormat == OutputFormat.Json;
            var isTabular = IsTabular(config.OutputFormat);
            var autoBlueprint = isTabular && config.OutputBlueprint is null ? IdentityMapping(ContainerLeafNames(groups)) : null;
            var effectiveBlueprint = autoBlueprint ?? config.OutputBlueprint;
            var flattensToRows = isTabular || effectiveBlueprint is { SchemaKind: OutputBlueprintSchemaKind.Flat };
            var groupsOutputFormat = isTabular ? config.OutputFormat : flattensToRows
                ? (isJson ? OutputFormat.Json : OutputFormat.Csv)
                : (isJson ? OutputFormat.Json : OutputFormat.Xml);
            steps.Add(new ExtractGroupStep { Roots = groups });
            return new ScrapingPlan
            {
                Steps = steps, OutputFormat = groupsOutputFormat, Engine = config.Engine,
                ScriptFileName = scriptFileName, OutputFileBaseName = outputFileBaseName,
                ChangeDetection = config.ChangeDetection, Proxy = config.Proxy, RequestDelay = config.RequestDelay, RespectRobotsDelay = config.RespectRobotsDelay ?? false, RobotsDisallow = config.RobotsDisallow, AppendOutput = config.AppendOutput ?? false, Retry = config.Retry, Headers = config.Headers, Deduplication = config.Deduplication, Hardening = config.Hardening,
                Pagination = config.Pagination, DiscoveredUrls = config.DiscoveredUrls,
                Preflight = config.Preflight ?? false,
                PersistentSession = config.PersistentSession ?? false,
                ExternalConfig = config.ExternalConfig ?? false,
                OutputBlueprint = effectiveBlueprint, OutputBlueprintAutoGenerated = autoBlueprint is not null,
            };
        }

        // Blocks mode: N extraction phases sharing this navigation; each block resolves its own name, output file
        // and format. ChangeDetection/Hardening live on the blocks, not on the plan (the outer config may not set
        // them), and ExternalConfig is rejected together with Blocks.
        if (config.Blocks is { Count: > 0 } blocksConfig)
        {
            var planBlocks = blocksConfig.Select((block, i) =>
            {
                var resolvedName = string.IsNullOrWhiteSpace(block.Name) ? $"block_{i + 1}" : block.Name.Trim();
                var outputFileBaseName = FileNameSanitizer.SanitizeBaseName(
                    string.IsNullOrWhiteSpace(block.OutputFileName) ? resolvedName : block.OutputFileName,
                    $"output_{i + 1}");
                var hasGroups = block.Groups is { Count: > 0 };
                var outputFormat = block.OutputFormat ?? (hasGroups ? OutputFormat.Xml : OutputFormat.Csv);

                return new PlanExtractionBlock
                {
                    Name = resolvedName,
                    Fields = hasGroups ? null : block.Fields?.Select(field => new ExtractStep
                    {
                        Name = field.Name, Selector = field.Selector, Attribute = field.Attribute,
                        FramePath = field.FramePath, Transforms = field.Transforms,
                        HiddenFromOutput = field.HiddenFromOutput,
                    }).ToList(),
                    Groups = hasGroups ? block.Groups : null,
                    OutputFormat = outputFormat,
                    OutputFileBaseName = outputFileBaseName,
                    ChangeDetection = block.ChangeDetection,
                    Hardening = block.Hardening,
                };
            }).ToList();

            steps.Add(new ExtractionBlockStep { Blocks = planBlocks });
            return new ScrapingPlan
            {
                Steps = steps, Engine = config.Engine,
                ScriptFileName = scriptFileName,
                Proxy = config.Proxy, RequestDelay = config.RequestDelay, RespectRobotsDelay = config.RespectRobotsDelay ?? false, RobotsDisallow = config.RobotsDisallow, AppendOutput = config.AppendOutput ?? false, Retry = config.Retry, Headers = config.Headers, Pagination = config.Pagination,
                PersistentSession = config.PersistentSession ?? false,
            };
        }

        // API mode: forces Engine.Api; the output defaults to Csv (flat shape) or Xml (tree), unless Json was
        // asked for. The blueprint / table-format rules are the same as for container mode above.
        if (config.Api is { } api)
        {
            var isJson = config.OutputFormat == OutputFormat.Json;
            var apiHasGroups = api.Groups is { Count: > 0 };
            var apiTabular = IsTabular(config.OutputFormat);
            var apiAutoBlueprint = apiTabular && apiHasGroups && config.OutputBlueprint is null ? IdentityMapping(ApiLeafNames(api.Groups!)) : null;
            var apiBlueprint = apiAutoBlueprint ?? config.OutputBlueprint;
            var apiFlattensToRows = apiHasGroups && apiBlueprint is { SchemaKind: OutputBlueprintSchemaKind.Flat };
            var apiOutputFormat = apiTabular ? config.OutputFormat : (apiHasGroups && !apiFlattensToRows)
                ? (isJson ? OutputFormat.Json : OutputFormat.Xml)
                : (isJson ? OutputFormat.Json : OutputFormat.Csv);
            steps.Add(new ApiCallStep { Config = api });
            return new ScrapingPlan
            {
                Steps = steps, OutputFormat = apiOutputFormat, Engine = ScrapingEngine.Api,
                ScriptFileName = scriptFileName, OutputFileBaseName = outputFileBaseName,
                ChangeDetection = config.ChangeDetection, Proxy = config.Proxy, RequestDelay = config.RequestDelay, RespectRobotsDelay = config.RespectRobotsDelay ?? false, RobotsDisallow = config.RobotsDisallow, AppendOutput = config.AppendOutput ?? false, Retry = config.Retry, Deduplication = config.Deduplication, Hardening = config.Hardening,
                PersistentSession = config.PersistentSession ?? false,
                ExternalConfig = config.ExternalConfig ?? false,
                OutputBlueprint = apiBlueprint, OutputBlueprintAutoGenerated = apiAutoBlueprint is not null,
            };
        }

        steps.AddRange(config.Fields.Select(field =>
            (ScrapingStep)new ExtractStep
            {
                Name = field.Name, Selector = field.Selector, Attribute = field.Attribute, FramePath = field.FramePath,
                Transforms = field.Transforms, Download = field.Download,
                MaxDownloadSizeBytes = field.MaxDownloadSizeBytes, AllowedContentTypes = field.AllowedContentTypes,
                HiddenFromOutput = field.HiddenFromOutput,
            }));

        return new ScrapingPlan
        {
            Steps = steps, OutputFormat = config.OutputFormat, Engine = config.Engine,
            ScriptFileName = scriptFileName, OutputFileBaseName = outputFileBaseName,
            ChangeDetection = config.ChangeDetection, Proxy = config.Proxy, RequestDelay = config.RequestDelay, RespectRobotsDelay = config.RespectRobotsDelay ?? false, RobotsDisallow = config.RobotsDisallow, AppendOutput = config.AppendOutput ?? false, Retry = config.Retry, Headers = config.Headers, Deduplication = config.Deduplication, Hardening = config.Hardening,
            Pagination = config.Pagination, DiscoveredUrls = config.DiscoveredUrls,
            Preflight = config.Preflight ?? false,
            PersistentSession = config.PersistentSession ?? false,
            ExternalConfig = config.ExternalConfig ?? false,
            OutputBlueprint = config.OutputBlueprint,
        };
    }

    private static ScrapingStep ToStep(BrowserAction action) => action switch
    {
        WaitForAction a => new WaitForStep { Selector = a.Selector, TimeoutMs = a.TimeoutMs, FramePath = a.FramePath },
        FillAction a => new FillStep
        {
            Selector = a.Selector, EnvironmentVariableName = a.EnvironmentVariableName, FramePath = a.FramePath,
        },
        ClickAction a => new ClickStep { Selector = a.Selector, FramePath = a.FramePath, Target = a.Target, WaitAfterMs = a.WaitAfterMs },
        ScrollAction a => new ScrollStep
        {
            ContainerSelector = a.ContainerSelector,
            LoadMoreButtonSelector = a.LoadMoreButtonSelector,
            MaxIterations = a.MaxIterations,
            WaitAfterMs = a.WaitAfterMs,
            ScrollStepPx = a.ScrollStepPx,
            FramePath = a.FramePath,
        },
        _ => throw new InvalidOperationException($"Unknown BrowserAction type: {action.GetType().Name}"),
    };

    private static bool IsTabular(OutputFormat format) => format is OutputFormat.Sqlite or OutputFormat.Xlsx;

    private static OutputBlueprintMapping IdentityMapping(IEnumerable<string> names) => new()
    {
        SchemaKind = OutputBlueprintSchemaKind.Flat,
        Fields = names.Select(name => new OutputBlueprintFieldMapping { TargetField = name, SourceField = name }).ToList(),
    };

    // Leaf field names in declaration order, without hidden ones.
    private static List<string> ContainerLeafNames(IEnumerable<ContainerNode> nodes)
    {
        var names = new List<string>();
        void Walk(IEnumerable<ContainerNode> ns)
        {
            foreach (var node in ns)
            {
                if (node is DataFieldNode field) { if (!field.HiddenFromOutput) names.Add(field.Name); }
                else if (node is GroupNode group) Walk(group.Children);
            }
        }
        Walk(nodes);
        return names;
    }

    private static List<string> ApiLeafNames(IEnumerable<ApiNode> nodes)
    {
        var names = new List<string>();
        void Walk(IEnumerable<ApiNode> ns)
        {
            foreach (var node in ns)
            {
                if (node is ApiField field) { if (!field.HiddenFromOutput) names.Add(field.Name); }
                else if (node is ApiGroup group) Walk(group.Children);
            }
        }
        Walk(nodes);
        return names;
    }
}
