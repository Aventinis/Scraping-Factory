using System.Text.RegularExpressions;
using ScrapingFactory.Compiler.Backends.Python;

namespace ScrapingFactory.Compiler.IR;

public static partial class ScrapingPlanValidator
{
    private static bool IsTabularFormat(OutputFormat format) => format is OutputFormat.Sqlite or OutputFormat.Xlsx;

    // Sqlite/Xlsx: a tree source is flattened by an identity (or the caller's flat) blueprint, so it needs unique field
    // names and a flat blueprint.
    private static string? ValidateTabularOutput(ScrapingPlan plan)
    {
        var blockWithTable = plan.Steps.OfType<ExtractionBlockStep>().SelectMany(step => step.Blocks)
            .FirstOrDefault(block => IsTabularFormat(block.OutputFormat));
        if (blockWithTable is not null)
            return $"Block '{blockWithTable.Name}': SQLite/Excel output is not supported for Blocks mode — use CSV, XML or JSON.";

        if (!IsTabularFormat(plan.OutputFormat))
            return null;

        var format = plan.OutputFormat == OutputFormat.Sqlite ? "SQLite" : "Excel";
        if (plan.ChangeDetection is not null)
            return $"{format} output cannot be combined with change detection (it compares the output as text) — use CSV or JSON.";
        if (plan.OutputBlueprint is { SchemaKind: OutputBlueprintSchemaKind.Tree })
            return $"{format} output needs a flat Output Blueprint (one table) — a nested (tree) blueprint cannot be written as a table.";

        if (plan.OutputBlueprintAutoGenerated)
        {
            var leafNames = plan.Steps.OfType<ExtractGroupStep>().SelectMany(step => CollectContainerFieldNames(step.Roots))
                .Concat(plan.Steps.OfType<ApiCallStep>().Where(step => step.Config.Groups is { Count: > 0 })
                    .SelectMany(step => CollectApiFieldNames(step.Config.Groups!)))
                .ToList();
            var duplicates = FindDuplicates(leafNames, name => name);
            if (duplicates.Count > 0)
                return $"{format} output writes a nested configuration as one table, so every data field needs a unique name — duplicate: {string.Join(", ", duplicates)}.";
        }

        return null;
    }

    // Key fields must be real fields of the current shape (leaf fields for trees; flat field names plus API parameter
    // names otherwise). A tree-shaped source with an Output Blueprint is rejected: the blueprint walkers re-read the
    // source tree and never see the deduplicated instances.
    private static string? ValidateDeduplication(DeduplicationConfig dedup, IReadOnlyCollection<string> availableFieldNames, bool isTreeShape, bool hasOutputBlueprint)
    {
        if (dedup.KeyFields.Count == 0)
            return "Deduplication needs at least one key field.";
        if (dedup.KeyFields.Any(string.IsNullOrWhiteSpace))
            return "Deduplication: key field names must not be blank.";
        var duplicateKey = FindDuplicates(dedup.KeyFields, name => name).FirstOrDefault();
        if (duplicateKey is not null)
            return $"Deduplication: duplicate key field '{duplicateKey}'.";
        var unknownKey = dedup.KeyFields.FirstOrDefault(name => !availableFieldNames.Contains(name));
        if (unknownKey is not null)
            return $"Deduplication: key field '{unknownKey}' does not match any field of this configuration.";

        if (dedup.Retention.Value <= 0)
            return "Deduplication: the retention value must be positive.";

        if (isTreeShape && hasOutputBlueprint)
            return "Deduplication is not supported together with an Output Blueprint on tree-shaped (container / API tree) output — writing a tree as SQLite/Excel flattens it the same way, so that counts too.";

        return null;
    }

    // availableSourceFields: flat ExtractStep names or Api-flat field names; API parameters are not mappable.
    private static string? ValidateOutputBlueprint(OutputBlueprintMapping mapping, IReadOnlyCollection<string> availableSourceFields)
    {
        if (mapping.Fields is not { Count: > 0 })
            return "OutputBlueprint needs at least one field mapping.";

        foreach (var entry in mapping.Fields)
        {
            if (string.IsNullOrWhiteSpace(entry.TargetField))
                return "OutputBlueprint: target field name must not be empty.";
            if (string.IsNullOrWhiteSpace(entry.SourceField))
                return $"OutputBlueprint: target field '{entry.TargetField}' needs a mapped source field.";
            if (!availableSourceFields.Contains(entry.SourceField))
                return $"OutputBlueprint: unknown source field '{entry.SourceField}' for target field '{entry.TargetField}'.";
        }

        var duplicateTargets = FindDuplicates(mapping.Fields, entry => entry.TargetField);
        if (duplicateTargets.Count > 0)
            return $"OutputBlueprint: duplicate target field(s): {string.Join(", ", duplicateTargets)}.";

        var duplicateSources = FindDuplicates(mapping.Fields, entry => entry.SourceField);
        if (duplicateSources.Count > 0)
            return $"OutputBlueprint: source field(s) mapped more than once: {string.Join(", ", duplicateSources)}.";

        return null;
    }

    // Tree counterpart: availableSourceFields is the leaf-field list. Duplicate target node names are allowed (they are only output tag names);
    // a source field may still be mapped only once.
    private static string? ValidateOutputBlueprintTree(List<OutputBlueprintTreeMappingNode>? tree, IReadOnlyCollection<string> availableSourceFields)
    {
        if (tree is not { Count: > 0 })
            return "OutputBlueprint: a tree-shaped mapping needs at least one target node.";

        var sourceFields = new List<string>();

        string? Walk(IEnumerable<OutputBlueprintTreeMappingNode> nodes)
        {
            foreach (var node in nodes)
            {
                if (string.IsNullOrWhiteSpace(node.Name))
                    return "OutputBlueprint: target node name must not be empty.";

                switch (node)
                {
                    case OutputBlueprintTreeMappingGroup group:
                        var childError = Walk(group.Children);
                        if (childError is not null)
                            return childError;
                        break;
                    case OutputBlueprintTreeMappingField field:
                        if (string.IsNullOrWhiteSpace(field.SourceField))
                            return $"OutputBlueprint: target field '{field.Name}' needs a mapped source field.";
                        if (!availableSourceFields.Contains(field.SourceField))
                            return $"OutputBlueprint: unknown source field '{field.SourceField}' for target field '{field.Name}'.";
                        sourceFields.Add(field.SourceField);
                        break;
                }
            }
            return null;
        }

        var error = Walk(tree);
        if (error is not null)
            return error;

        if (sourceFields.Count == 0)
            return "OutputBlueprint needs at least one field mapping.";

        var duplicateSources = FindDuplicates(sourceFields, name => name);
        if (duplicateSources.Count > 0)
            return $"OutputBlueprint: source field(s) mapped more than once: {string.Join(", ", duplicateSources)}.";

        return null;
    }
}
