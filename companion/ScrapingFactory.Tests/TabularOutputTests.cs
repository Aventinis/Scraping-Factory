using ScrapingFactory.Compiler.Backends.Python;
using ScrapingFactory.Compiler.IR;
using Xunit;

namespace ScrapingFactory.Tests;

// Issue #229: SQLite / Excel output — plan building (tree sources are
// flattened through an identity Output Blueprint), validation of the
// unsupported combinations, and real script runs whose written file is read
// back by the verifier (the Xlsx cases need `openpyxl`, which CI installs).
public class TabularOutputTests
{
    // ── Builder: tree sources are flattened ───────────────────────────────────

    private static ScrapingConfig ContainerConfig(OutputFormat format, OutputBlueprintMapping? blueprint = null) => new()
    {
        Url = "https://example.com",
        OutputFormat = format,
        OutputBlueprint = blueprint,
        Groups =
        [
            new GroupNode
            {
                Name = "Kategorie", Selector = ".cat", Repeating = true,
                Children =
                [
                    new DataFieldNode { Name = "Titel", Selector = "h2", Mode = ExtractMode.Text },
                    new DataFieldNode { Name = "Intern", Selector = ".x", Mode = ExtractMode.Text, HiddenFromOutput = true },
                    new GroupNode
                    {
                        Name = "Artikel", Selector = ".item", Repeating = true,
                        Children = [new DataFieldNode { Name = "Name", Selector = ".n", Mode = ExtractMode.Text }],
                    },
                ],
            },
        ],
    };

    [Fact]
    public void Container_WithSqlite_GetsAnIdentityBlueprintOverTheVisibleLeafFields()
    {
        var plan = ScrapingPlanBuilder.Build(ContainerConfig(OutputFormat.Sqlite));

        Assert.Equal(OutputFormat.Sqlite, plan.OutputFormat);
        Assert.True(plan.OutputBlueprintAutoGenerated);
        Assert.Equal(["Titel", "Name"], plan.OutputBlueprint!.Fields!.Select(f => f.TargetField));
        Assert.True(ScrapingPlanValidator.Validate(plan).Success);
    }

    [Fact]
    public void Container_WithAnExplicitFlatBlueprint_KeepsIt()
    {
        var blueprint = new OutputBlueprintMapping
        {
            Fields = [new OutputBlueprintFieldMapping { TargetField = "Artikelname", SourceField = "Name" }],
        };
        var plan = ScrapingPlanBuilder.Build(ContainerConfig(OutputFormat.Xlsx, blueprint));

        Assert.False(plan.OutputBlueprintAutoGenerated);
        Assert.Same(blueprint, plan.OutputBlueprint);
        Assert.Equal(OutputFormat.Xlsx, plan.OutputFormat);
    }

    [Fact]
    public void Container_WithoutATableFormat_StaysATree()
    {
        var plan = ScrapingPlanBuilder.Build(ContainerConfig(OutputFormat.Csv));
        Assert.Equal(OutputFormat.Xml, plan.OutputFormat);
        Assert.Null(plan.OutputBlueprint);
    }

    // ── Validation ───────────────────────────────────────────────────────────

    private static ScrapingPlan FlatPlan(OutputFormat format, Action<ScrapingConfigBuilder>? configure = null)
    {
        var builder = new ScrapingConfigBuilder { Format = format };
        configure?.Invoke(builder);
        return ScrapingPlanBuilder.Build(new ScrapingConfig
        {
            Url = "https://example.com", OutputFormat = format,
            Fields = [new ScrapingField { Name = "Titel", Selector = "h1" }],
            ChangeDetection = builder.ChangeDetection, Deduplication = builder.Deduplication,
        });
    }

    private sealed class ScrapingConfigBuilder
    {
        public OutputFormat Format { get; init; }
        public ChangeDetectionConfig? ChangeDetection { get; set; }
        public DeduplicationConfig? Deduplication { get; set; }
    }

    [Theory]
    [InlineData(OutputFormat.Sqlite)]
    [InlineData(OutputFormat.Xlsx)]
    public void Validate_FlatPlan_Passes(OutputFormat format) =>
        Assert.True(ScrapingPlanValidator.Validate(FlatPlan(format)).Success);

    [Fact]
    public void Validate_ChangeDetection_IsRejected()
    {
        var plan = FlatPlan(OutputFormat.Sqlite, b => b.ChangeDetection = new ChangeDetectionConfig
        {
            Notify = "Webhook", Webhook = new WebhookNotificationConfig { UrlEnvVar = "HOOK" },
        });
        var result = ScrapingPlanValidator.Validate(plan);
        Assert.False(result.Success);
        Assert.Contains("change detection", result.Error);
    }

    [Fact]
    public void Validate_DeduplicationAppend_IsRejected()
    {
        var plan = FlatPlan(OutputFormat.Xlsx, b => b.Deduplication = new DeduplicationConfig
        {
            KeyFields = ["Titel"], Incremental = true, IncrementalOutput = IncrementalOutputMode.Append,
        });
        var result = ScrapingPlanValidator.Validate(plan);
        Assert.False(result.Success);
        Assert.Contains("append", result.Error);
    }

    [Fact]
    public void Validate_TreeSchemaBlueprint_IsRejected()
    {
        var blueprint = new OutputBlueprintMapping
        {
            SchemaKind = OutputBlueprintSchemaKind.Tree,
            Tree = [new OutputBlueprintTreeMappingField { Name = "Titel", SourceField = "Titel" }],
        };
        var result = ScrapingPlanValidator.Validate(ScrapingPlanBuilder.Build(ContainerConfig(OutputFormat.Sqlite, blueprint)));
        Assert.False(result.Success);
        Assert.Contains("flat Output Blueprint", result.Error);
    }

    [Fact]
    public void Validate_DuplicateLeafNamesInATree_ExplainTheTableConstraint()
    {
        var config = ContainerConfig(OutputFormat.Xlsx);
        var group = (GroupNode)config.Groups![0];
        var duplicated = new ScrapingConfig
        {
            Url = config.Url, OutputFormat = OutputFormat.Xlsx,
            Groups = [new GroupNode { Name = group.Name, Selector = group.Selector, Repeating = true,
                Children = [new DataFieldNode { Name = "Titel", Selector = "h2", Mode = ExtractMode.Text },
                            new DataFieldNode { Name = "Titel", Selector = "h3", Mode = ExtractMode.Text }] }],
        };
        var result = ScrapingPlanValidator.Validate(ScrapingPlanBuilder.Build(duplicated));
        Assert.False(result.Success);
        Assert.Contains("unique name", result.Error);
    }

    [Fact]
    public void Validate_BlocksWithATableFormat_IsRejected()
    {
        var plan = new ScrapingPlan
        {
            Steps =
            [
                new NavigateStep { Urls = ["https://example.com"] },
                new ExtractionBlockStep
                {
                    Blocks =
                    [
                        new PlanExtractionBlock { Name = "a", Fields = [new ExtractStep { Name = "x", Selector = "h1" }], OutputFormat = OutputFormat.Sqlite, OutputFileBaseName = "a" },
                        new PlanExtractionBlock { Name = "b", Fields = [new ExtractStep { Name = "x", Selector = "h1" }], OutputFormat = OutputFormat.Csv, OutputFileBaseName = "b" },
                    ],
                },
            ],
        };
        var result = ScrapingPlanValidator.Validate(plan);
        Assert.False(result.Success);
        Assert.Contains("Blocks mode", result.Error);
    }

    // ── Real runs ────────────────────────────────────────────────────────────

    private const string Listing = "<html><body>"
        + "<div class='cat'><h2>Obst</h2><div class='item'><span class='n'>Apfel</span></div><div class='item'><span class='n'>Birne</span></div></div>"
        + "<div class='cat'><h2>Gemuese</h2><div class='item'><span class='n'>Karotte</span></div></div>"
        + "</body></html>";

    private static async Task<(ScrapingFactory.Compiler.Backends.ScriptVerificationResult Result, byte[] Bytes)> RunAsync(
        ScrapingPlan plan, Func<ScrapingPlan, string> generate)
    {
        var result = await new PythonScriptVerifier().VerifyAsync(
            generate(plan), plan.OutputFormat, plan.OutputFileBaseName, includePreview: true, includeOutputFile: true);
        Assert.True(result.Success, result.Error);
        Assert.Equal("base64", result.OutputFileEncoding);
        return (result, Convert.FromBase64String(result.OutputFileContent!));
    }

    private static List<string[]> PreviewRows(ScrapingFactory.Compiler.Backends.ScriptVerificationResult result) =>
        result.Preview!.Rows!.Select(row => result.Preview!.Columns!.Select(column => row[column]).ToArray()).ToList();

    [Theory]
    [InlineData(OutputFormat.Sqlite, "SQLite format 3")]
    [InlineData(OutputFormat.Xlsx, "PK")]
    public async Task FlatStatic_WritesTheTableFile(OutputFormat format, string magic)
    {
        using var server = new LocalTestServer("<html><body><ul><li class='n'>Kaffee</li><li class='n'>Tee</li></ul></body></html>");
        var plan = ScrapingPlanBuilder.Build(new ScrapingConfig
        {
            Url = server.BaseUrl, OutputFormat = format, OutputFileName = "tabelle",
            Fields = [new ScrapingField { Name = "Name", Selector = "li.n" }],
        });

        var (result, bytes) = await RunAsync(plan, p => new PythonCodeGenerator().Generate(p));

        Assert.Equal("tabelle." + (format == OutputFormat.Sqlite ? "sqlite" : "xlsx"), result.OutputFileName);
        Assert.StartsWith(magic, System.Text.Encoding.Latin1.GetString(bytes.Take(16).ToArray()));
        Assert.Equal(2, result.RowCount);
        Assert.Equal(["Name"], result.Preview!.Columns);
        Assert.Equal([["Kaffee"], ["Tee"]], PreviewRows(result));
    }

    [Theory]
    [InlineData(OutputFormat.Sqlite)]
    [InlineData(OutputFormat.Xlsx)]
    public async Task Container_IsFlattenedOneRowPerInnermostInstance(OutputFormat format)
    {
        using var server = new LocalTestServer(Listing);
        var config = ContainerConfig(format);
        var plan = ScrapingPlanBuilder.Build(new ScrapingConfig { Url = server.BaseUrl, OutputFormat = format, Groups = config.Groups });

        var (result, _) = await RunAsync(plan, p => new PythonCodeGenerator().Generate(p));

        Assert.Equal(["Titel", "Name"], result.Preview!.Columns);
        // The category title is repeated into every row beneath it.
        Assert.Equal([["Obst", "Apfel"], ["Obst", "Birne"], ["Gemuese", "Karotte"]], PreviewRows(result));
    }

    [Fact]
    public async Task Browser_Sqlite_Works()
    {
        using var server = new LocalTestServer("<html><body><p class='n'>Eins</p><p class='n'>Zwei</p></body></html>");
        var plan = ScrapingPlanBuilder.Build(new ScrapingConfig
        {
            Url = server.BaseUrl, Engine = ScrapingEngine.Browser, OutputFormat = OutputFormat.Sqlite,
            Fields = [new ScrapingField { Name = "Zahl", Selector = "p.n" }],
        });

        var (result, _) = await RunAsync(plan, p => new PythonPlaywrightCodeGenerator().Generate(p));

        Assert.Equal([["Eins"], ["Zwei"]], PreviewRows(result));
    }

    [Theory]
    [InlineData(OutputFormat.Sqlite)]
    [InlineData(OutputFormat.Xlsx)]
    public async Task ApiFlat_WritesTheTableFile(OutputFormat format)
    {
        using var server = new LocalTestServer(_ => new LocalTestServerResponse("""{ "items": [ { "t": "a" }, { "t": "b" } ] }""", "application/json"));
        var plan = ScrapingPlanBuilder.Build(new ScrapingConfig
        {
            Url = server.BaseUrl, OutputFormat = format,
            Api = new ApiConfig
            {
                UrlTemplate = server.BaseUrl + "items", ItemsPath = "items",
                Fields = [new ApiField { Name = "T", Path = "t" }],
            },
        });

        var (result, _) = await RunAsync(plan, p => new PythonApiCodeGenerator().Generate(p));

        Assert.Equal([["a"], ["b"]], PreviewRows(result));
    }

    [Fact]
    public async Task ApiTree_IsFlattenedToo()
    {
        using var server = new LocalTestServer(_ => new LocalTestServerResponse(
            """{ "cats": [ { "name": "Obst", "items": [ { "n": "Apfel" }, { "n": "Birne" } ] }, { "name": "Gemuese", "items": [ { "n": "Karotte" } ] } ] }""", "application/json"));
        var plan = ScrapingPlanBuilder.Build(new ScrapingConfig
        {
            Url = server.BaseUrl, OutputFormat = OutputFormat.Sqlite,
            Api = new ApiConfig
            {
                UrlTemplate = server.BaseUrl + "data",
                Groups =
                [
                    new ApiGroup
                    {
                        Name = "Kategorie", Path = "cats",
                        Children =
                        [
                            new ApiField { Name = "Titel", Path = "name" },
                            new ApiGroup { Name = "Artikel", Path = "items", Children = [new ApiField { Name = "Name", Path = "n" }] },
                        ],
                    },
                ],
            },
        });

        var (result, _) = await RunAsync(plan, p => new PythonApiCodeGenerator().Generate(p));

        Assert.Equal([["Obst", "Apfel"], ["Obst", "Birne"], ["Gemuese", "Karotte"]], PreviewRows(result));
    }

    [Fact]
    public async Task Xlsx_KeepsAValueStartingWithEqualsAsText()
    {
        using var server = new LocalTestServer("<html><body><p class='n'>=1+1</p></body></html>");
        var plan = ScrapingPlanBuilder.Build(new ScrapingConfig
        {
            Url = server.BaseUrl, OutputFormat = OutputFormat.Xlsx,
            Fields = [new ScrapingField { Name = "Wert", Selector = "p.n" }],
        });

        var (result, _) = await RunAsync(plan, p => new PythonCodeGenerator().Generate(p));

        Assert.Equal([["=1+1"]], PreviewRows(result));
    }

    [Fact]
    public async Task NoData_FailsLikeAnyOtherFormat()
    {
        using var server = new LocalTestServer("<html><body><p>nothing</p></body></html>");
        var plan = ScrapingPlanBuilder.Build(new ScrapingConfig
        {
            Url = server.BaseUrl, OutputFormat = OutputFormat.Sqlite,
            Fields = [new ScrapingField { Name = "Wert", Selector = "p.n" }],
        });

        var result = await new PythonScriptVerifier().VerifyAsync(new PythonCodeGenerator().Generate(plan), OutputFormat.Sqlite);

        Assert.False(result.Success);
    }
}
